def lead_card(lead: Lead, for_admin: bool = False) -> str:
    lines = [
        f"<b>Заявка №{lead.id}</b> — {lead.status_text}",
        f"Услуга: {escape(lead.service)}",
        f"Имя: {escape(lead.name)}",
        f"Телефон: {escape(lead.phone)}",
        f"Описание: {escape(lead.description)}",
        f"Создана: {lead.created_at}",
    ]
    if for_admin:
        user = f"@{lead.username}" if lead.username else "профиль"
        lines.append(f'Клиент: <a href="tg://user?id={lead.user_id}">{escape(user)}</a>')
    return "\n".join(lines)


def preview(data: dict) -> str:
    return (
        "<b>Проверьте заявку:</b>\n\n"
        f"Услуга: {escape(data['service'])}\n"
        f"Имя: {escape(data['name'])}\n"
        f"Телефон: {escape(data['phone'])}\n"
        f"Описание: {escape(data['description'])}"
    )


def client_label(lead: Lead) -> str:
    return f"👤 <b>{escape(lead.name)}</b> · заявка №{lead.id}"
